/**
 * Récupère les paramètres de traduction pour une activité donnée.
 */
export function getH5PLocalization(lang, activityType) {
    const texts = H5P_TRANSLATIONS[lang] || H5P_TRANSLATIONS['Français'];

    // --- 1. VRAI / FAUX ---
    if (activityType === 'TrueFalse') {
        return {
            trueText: texts.trueText,
            falseText: texts.falseText,
            score: texts.scoreBarLabel, 
            checkAnswer: texts.checkAnswer,
            showSolutionButton: texts.showSolution,
            tryAgain: texts.retry,
            result: texts.result
        };
    }

    // --- 2. QCM ---
    if (activityType === 'MultiChoice') {
        return {
            checkAnswerButton: texts.checkAnswer,
            showSolutionButton: texts.showSolution,
            tryAgainButton: texts.retry,
            tipsLabel: texts.tipLabel,
            scoreBarLabel: texts.scoreBarLabel, 
            tipAvailable: texts.tipLabel + " disponible",
            feedbackAvailable: texts.feedbackAvailable,
            readFeedback: texts.readFeedback,
            submitAnswerButton: texts.submitAnswer,
            wrongAnswer: texts.falseText,
            correctAnswer: texts.trueText,
            shouldCheck: "Devrait être coché", 
            shouldNotCheck: "Ne devrait pas être coché", 
            noInput: "Veuillez répondre avant de vérifier"
        };
    }
    
    // --- 3. MOTS MÊLÉS ---
    if (activityType === 'FindTheWords') {
        return {
            check: texts.checkAnswer,
            tryAgain: texts.retry,
            showSolution: texts.showSolution,
            found: texts.result + " : @found / @totalWords", 
            timeSpent: texts.timeSpent, 
            score: texts.scoreBarLabel.replace(':num', '@score').replace(':total', '@total'),
            wordListHeader: texts.wordListHeader
        };
    }

    // --- 4. TEXTE À TROUS ---
    if (activityType === 'DragText') {
        return {
            checkAnswer: texts.checkAnswer,
            showSolution: texts.showSolution,
            tryAgain: texts.retry,
            scoreBarLabel: texts.scoreBarLabel 
        };
    }
    
    // --- 5. MOTS CROISÉS ---
    if (activityType === 'Crossword') {
         return {
            "across": texts.crosswordAcross,
            "down": texts.crosswordDown,
            "acrossLabel": texts.crosswordAcross,
            "downLabel": texts.crosswordDown,
            "checkAnswer": texts.checkAnswer,
            "submitAnswer": texts.submitAnswer,
            "tryAgain": texts.retry,
            "showSolution": texts.showSolution,
            "couldNotGenerateCrossword": "Grille impossible à générer. Réduisez le nombre de mots.",
            "problemDemonstration": "Problème..."
        };
    }
    
    // --- 6. TRIER LES PARAGRAPHES ---
    if (activityType === 'SortParagraphs') {
        return {
            checkAnswer: texts.checkAnswer,
            tryAgain: texts.retry,
            showSolution: texts.showSolution,
            correct: texts.trueText,
            incorrect: texts.falseText,
            scoreBarLabel: texts.scoreBarLabel
        };
    }

    // --- 7. DICTÉE ---
    if (activityType === 'Dictation') {
        return {
            "checkAnswer": texts.checkAnswer,
            "showSolution": texts.showSolution,
            "tryAgain": texts.retry,
            "play": texts.play || "Play",
            "pause": texts.pause || "Pause",
            "sentence": texts.sentenceKey || "Sentence @n",
            "generalFeedback": texts.dictationMistakes || "You have made @total mistake(s).",
            "a11yCheck": texts.checkAnswer,
            "a11yShowSolution": texts.showSolution,
            "a11yRetry": texts.retry,
            "a11yPlay": texts.play,
            "a11yPause": texts.pause
        };
    }

    // --- 8. RÉSUMÉ ---
    if (activityType === 'Summary') {
        return {
            "name": "Résumé",
            "intro": "Choisissez la bonne proposition.",
            "solvedLabel": texts.progress, 
            "scoreLabel": texts.score, 
            "resultLabel": texts.result,       
            "showSolution": texts.showSolution,
            "retry": texts.retry,
            "labelCorrect": texts.trueText,
            "labelIncorrect": texts.falseText
        };
    }

    // --- 9. REPÉRER LES MOTS ---
    if (activityType === 'MarkTheWords') {
        return {
            checkAnswerButton: texts.checkAnswer,
            tryAgainButton: texts.retry,
            showSolutionButton: texts.showSolution,
            scoreBarLabel: texts.scoreBarLabel,
            correctAnswer: texts.trueText,
            incorrectAnswer: texts.falseText,
            missedAnswer: "Manquant"
        };
    }

    // --- 10. QUESTION SET (Global Quiz/TF) ---
    if (activityType === 'QuestionSet') {
        return {
            // Textes généraux
            "yourResult": texts.qsYourResult || "Vos résultats :",
            "noResultMessage": texts.qsNoResult || "Terminé",
            
            // Variantes pour "Terminer"
            "finishButtonLabel": texts.qsFinish || "Terminer",
            "finishButtonText": texts.qsFinish || "Terminer",
            "finishButton": texts.qsFinish || "Terminer",
            
            // Variantes pour "Recommencer"
            "retryButtonLabel": texts.retry,
            "retryButtonText": texts.retry,
            
            // Variantes pour "Voir la solution"
            "solutionButtonLabel": texts.showSolution,
            "solutionButtonText": texts.showSolution,
            
            // Variantes pour "Soumettre / Vérifier"
            "submitButtonText": texts.qsSubmit || "Vérifier",
            "submitButton": texts.qsSubmit || "Vérifier",
            
            // Navigation
            "prevButtonLabel": texts.qsPrevious || "Précédent",
            "nextButtonLabel": texts.qsNext || "Suivant",
            "prevButton": texts.qsPrevious || "Précédent",
            "nextButton": texts.qsNext || "Suivant",
            
            "questionLabel": texts.qsQuestion || "Question"
        };
    }


// --- 11. FLASHCARDS (Mode Exercice) ---
    // ✅ MISE À JOUR COMPLÈTE
	if (activityType === 'Flashcards') {
	        return {
	            // Navigation
	            progressText: texts.cardProgress,
	            next: texts.qsNext || "Suivant",
	            previous: texts.qsPrevious || "Précédent",
            
	            // Interaction
	            checkAnswerText: texts.flashCheckAnswer || "Vérifier",
	            defaultAnswerText: texts.flashDefaultAnswer || "Votre réponse",
            
	            // Feedback Immédiat
	            correctAnswerText: texts.flashCorrect || "Réponse exacte",
	            incorrectAnswerText: texts.flashIncorrect || "Réponse inexacte",
	            solutionLabel: texts.flashSolutionLabel || "Bonne(s) réponse(s)",
	            showSolutionTitle: texts.flashSolutionTitle || "Réponse(s) correcte(s)",
	            showSolutionButton: texts.flashShowSolution || "Voir la solution",
	            tryAgainText: texts.flashRetry || "Recommencer",

	            // ✅ ÉCRAN DE RÉSULTATS (Ce qu'il manquait)
	            results: texts.flashResults || "Résultats",
	            showResults: texts.flashShowResults || "Afficher les résultats",
	            ofCorrect: texts.flashOfCorrect || "@score sur @total correctes"
	        };
	    }


   
	// --- 12. DIALOG CARDS (Mode Révision) ---
	    if (activityType === 'Dialogcards') {
	        return {
	            turnCardText: texts.turnCard,            // "Retourner"
	            retryText: texts.retry,                  // "Recommencer"
	            nextText: texts.qsNext || "Suivant",
	            prevText: texts.qsPrevious || "Précédent",
	            progressText: texts.cardProgress,        // "Carte @card sur @total"
	            cardFrontLabel: texts.cardFront,         // "Face avant"
	            cardBackLabel: texts.cardBack            // "Face arrière"
	        };
	    }

	
	// Dans getH5PLocalization...
	    // --- 13. TIMELINE ---
	    if (activityType === 'Timeline') {
	        return {
	            "zoomIn": "Zoomer",
	            "zoomOut": "Dézoomer",
	            "swipeLeft": "Glisser gauche",
	            "swipeRight": "Glisser droite"
	        };
	    }

	// --- 14. APPRIEMENT D'IMAGES (Image Pairing) ---
	    if (activityType === 'ImagePair' || activityType === 'ImagePairing') {
	        return {
	            checkAnswer: texts.checkAnswer,       // "Vérifier"
	            tryAgain: texts.retry,                // "Recommencer"
	            showSolution: texts.showSolution,     // "Voir la solution"
	            // H5P Image Pairing utilise @score et @total, on remplace les placeholders de base (:num/:total)
	            score: texts.scoreBarLabel.replace(':num', '@score').replace(':total', '@total') 
	        };
	    }
		
	// --- 15. TEXTES À TROUS AVANCÉS (Advanced Blanks) ---
	    if (activityType === 'AdvancedBlanks') {
	        return {
	            checkAnswer: texts.checkAnswer,
	            submitAnswer: texts.submitAnswer || texts.checkAnswer,
	            tryAgain: texts.retry,
	            showSolution: texts.showSolution,
	            scoreBarLabel: texts.scoreBarLabel,
	            tipLabel: texts.tipLabel,
	            answeredCorrectly: texts.flashCorrect || texts.trueText,
	            answeredIncorrectly: texts.flashIncorrect || texts.falseText,
	            solutionLabel: texts.flashSolutionLabel || texts.trueText,
            
	            // Textes spécifiques au module
	            notFilledOut: texts.abNotFilledOut,
	            answerIsCorrect: texts.abAnswerIsCorrect,
	            answerIsWrong: texts.abAnswerIsWrong,
	            spellingMistake: texts.abSpellingMistake,
	            emptyAnswer: texts.abEmptyAnswer,
	            emptyAnswerWithSolution: texts.abEmptyAnswerWithSolution,
            
	            // Boîtes de dialogue de confirmation
	            confirmCheck: {
	                header: texts.checkAnswer,
	                body: texts.abConfirmCheckBody,
	                cancelLabel: texts.abCancel,
	                confirmLabel: texts.checkAnswer
	            },
	            confirmRetry: {
	                header: texts.retry,
	                body: texts.abConfirmRetryBody,
	                cancelLabel: texts.abCancel,
	                confirmLabel: texts.retry
	            }
	        };
	    }

	// --- 16. GLISSER-DÉPOSER (Drag & Drop) ---
	    if (activityType === 'DragNDrop' || activityType === 'DragQuestion') {
	        return {
	            checkAnswer: texts.checkAnswer,
	            tryAgain: texts.retry,
	            showSolution: texts.showSolution,
	            scoreBarLabel: texts.scoreBarLabel,
            
	            // Textes spécifiques au Glisser-Déposer
	            scoreExplanationButtonLabel: texts.ddScoreExplanation,
	            feedbackHeader: texts.ddFeedbackHeader,
	            dropZoneIndexLabel: texts.ddDropZone + " @index",
	            draggableTextLabel: texts.ddDraggable + " @text",
            
	            // Accessibilité
	            a11yCheck: texts.checkAnswer,
	            a11yRetry: texts.retry,
	            a11yShowSolution: texts.showSolution
	        };
	    }
		
	// --- 17. VIDÉO INTERACTIVE ---
	    if (activityType === 'InteractiveVideo') {
	        return {
	            interaction: texts.ivInteraction,
	            play: texts.ivPlay,
	            pause: texts.ivPause,
	            mute: texts.ivMute,
	            unmute: texts.ivUnmute,
	            quality: texts.ivQuality,
	            fullscreen: texts.ivFullscreen,
	            exitFullscreen: texts.ivExitFullscreen,
	            captions: texts.ivCaptions,
	            close: texts.ivClose,
	            navDisabled: texts.ivNavDisabled,
	            continueWithVideo: texts.ivContinueWithVideo,
	            continue: texts.ivContinue
	        };
	    }
	

    return {}; // Fin de la fonction
}

